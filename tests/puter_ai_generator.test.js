import { test, describe } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { getFreeToolBySlug } from '../src/services/aiCatalogService.ts';
import { extractChatText } from '../src/lib/utilities/puterChat.ts';

const read = (relative) => fs.readFileSync(path.resolve(process.cwd(), relative), 'utf8');

describe('Puter.js AI Generator (/free-tools/ai-generator)', () => {
  test('route exists and resolves to the free-tool detail page', async () => {
    const { matchRoute } = await import('../dist/test-ssr.js');
    assert.deepEqual(matchRoute('/free-tools/ai-generator'), {
      route: 'free-tool-detail',
      params: { slug: 'ai-generator' },
    });
  });

  test('registry entry exists with the right slug and an honest client-side flag', () => {
    const tool = getFreeToolBySlug('ai-generator');
    assert.ok(tool, 'ai-generator must be registered');
    assert.equal(tool.slug, 'ai-generator');
    assert.equal(tool.id, 'ai-generator');
    assert.equal(tool.name, 'AI Text, Image & Video Generator');
    // This tool calls Puter's third-party API: it is NOT client-side-only,
    // and the flag must say so instead of claiming local processing.
    assert.equal(tool.isClientSideOnly, false);
    assert.ok(tool.description.includes('Puter'), 'description must name Puter as the provider');
  });

  test('tool component references the official Puter.js CDN and the real API', () => {
    const source = read('src/components/utilities/UtilityAiTools.tsx');
    assert.ok(source.includes('https://js.puter.com/v2/'), 'must load Puter.js from the official CDN URL');
    assert.ok(source.includes('puter.ai.chat('), 'text mode must call puter.ai.chat()');
    assert.ok(source.includes('puter.ai.txt2img('), 'image mode must call puter.ai.txt2img()');
    assert.ok(source.includes('puter.ai.txt2vid('), 'video mode must call puter.ai.txt2vid()');
    assert.ok(source.includes('puter.auth.signIn()'), 'must call the real Puter sign-in');
    assert.ok(source.includes('puter.auth.isSignedIn()'), 'must detect signed-in state via puter.auth.isSignedIn()');
    // Text/image pass no model argument (provider default); video passes the
    // documented Wan 2.7 default explicitly — no invented model names anywhere.
    assert.ok(source.includes('puter.ai.chat(trimmed)'), 'text call must not pass a model');
    assert.ok(source.includes('puter.ai.txt2img(trimmed)'), 'image call must not pass a model');
    assert.ok(source.includes("model: PUTER_VIDEO_MODEL"), 'video call must name its model explicitly');
    assert.ok(source.includes("togetherai:wan-ai/wan2.7-t2v"), 'video model must be the documented Wan 2.7 default');
    assert.ok(source.includes('seconds: PUTER_VIDEO_SECONDS'), 'video call must cap duration');
    assert.ok(source.includes('size: PUTER_VIDEO_SIZE'), 'video call must cap resolution');
    // index.html must NOT load Puter.js globally; the tool loads it on mount only.
    assert.ok(!read('index.html').includes('js.puter.com'), 'Puter.js must not be added to index.html');
    // The shipped code never asks for a sample clip; sample mode is validation-only.
    assert.ok(!source.includes('testMode') && !source.includes('test_mode'), 'shipped code must not request a sample clip');
  });

  test('honest loading, sign-in, error and disclosure states render', () => {
    const source = read('src/components/utilities/UtilityAiTools.tsx');
    assert.ok(source.includes('Loading Puter.js'), 'script-loading state must be shown');
    assert.ok(source.includes('Sign in with Puter to generate'), 'not-signed-in state must be honest');
    assert.ok(source.includes('Could not reach Puter'), 'network failure must surface an honest error');
    assert.ok(source.includes('Retry'), 'errors must offer a retry, never a fake success');
    assert.ok(source.includes('third-party AI service'), 'page must disclose Puter as a third party');
    assert.ok(source.includes('your own free Puter account'), 'page must disclose the User-Pays account model');
    assert.ok(source.includes('SwitchRoute pays nothing and charges nothing'), 'page must state SwitchRoute charges nothing');
    assert.ok(source.includes('AI-generated by'), 'page must label output as AI-generated');
    assert.ok(!source.includes('sample') && !source.includes('Mock'), 'no mock or sample results may be shown as generated');
  });

  test('no overpromising wording appears in the page copy', () => {
    const banned = [['unlimited', 'free'].join(' '), ['unlimited', 'free', 'video'].join(' ')];
    for (const file of [
      'src/components/utilities/UtilityAiTools.tsx',
      'src/data/freeToolsData.ts',
      'src/pages/FreeToolDetailPage.tsx',
      'src/pages/FreeToolsPage.tsx',
    ]) {
      for (const phrase of banned) {
        assert.ok(!read(file).toLowerCase().includes(phrase), `${file} must not promise "${phrase}"`);
      }
    }
  });

  test('switching modes abandons a running generation instead of leaving the UI stuck', () => {
    const source = read('src/components/utilities/UtilityAiTools.tsx');
    assert.ok(source.includes('requestRef'), 'generations must be gated by request id');
    assert.ok(source.includes('isCurrent()'), 'late results must only apply when still current');
    assert.ok(source.includes('requestRef.current += 1'), 'a mode switch must invalidate the running request');
    assert.ok(source.includes('setGenerating(false)'), 'a mode switch must clear the generating state');
  });

  test('video mode renders honestly: waiting state, player, download, timeout and funds errors', () => {
    const source = read('src/components/utilities/UtilityAiTools.tsx');
    assert.ok(source.includes('Video'), 'a Video mode tab must exist');
    assert.ok(source.includes('Generating your clip, this can take a while'), 'video must show an honest waiting state');
    assert.ok(source.includes('not a progress estimate'), 'waiting state must not fake progress');
    assert.ok(!source.includes('<progress'), 'no fake progress bar may be rendered');
    assert.ok(source.includes('<video'), 'generated clip must render in a <video> player');
    assert.ok(source.includes('controls'), 'video player must have play controls');
    assert.ok(source.includes('Download video'), 'generated clip must offer a download');
    assert.ok(source.includes('Puter timed out waiting for the clip'), 'video timeout must surface honestly');
    assert.ok(source.includes('cannot cover this generation'), 'insufficient Puter balance must surface honestly');
    assert.ok(source.includes('Video costs far more credits'), 'page must say video costs far more credits');
    assert.ok(source.includes('5 seconds, 720p'), 'page must state the modest video defaults');
    assert.ok(source.includes('PUTER_VIDEO_SECONDS = 5'), 'video duration default must be 5 seconds');
    assert.ok(source.includes("PUTER_VIDEO_SIZE = '720x1280'"), 'video size default must be the 720P tier');
  });

  test('chat reply extraction handles the documented string shape and object shapes', () => {
    assert.equal(extractChatText('hello'), 'hello');
    assert.equal(extractChatText({ text: 'from text field' }), 'from text field');
    assert.equal(extractChatText({ message: { content: 'from message' } }), 'from message');
    assert.equal(
      extractChatText({ message: { content: [{ text: 'a' }, { text: 'b' }] } }),
      'ab',
    );
    assert.equal(extractChatText(null), '');
    assert.equal(extractChatText(undefined), '');
    assert.equal(extractChatText({}), '');
  });

  test('sitemap lists the new URL exactly once, and the detail page discloses the provider', () => {
    const sitemap = read('public/sitemap.xml');
    const matches = sitemap.match(/https:\/\/switchroute\.in\/free-tools\/ai-generator/g) || [];
    assert.equal(matches.length, 1, 'sitemap must list the new URL exactly once');
    const freeToolUrls = sitemap.match(/https:\/\/switchroute\.in\/free-tools\/[a-z0-9-]+/g) || [];
    assert.equal(new Set(freeToolUrls).size, 8, 'sitemap must list exactly 8 free-tools URLs');
    const detail = read('src/pages/FreeToolDetailPage.tsx');
    assert.ok(detail.includes('Third-party AI (Puter)'), 'detail page must badge the tool as third-party Puter AI');
    assert.ok(detail.includes('Prompts are sent to Puter'), 'detail page policy note must disclose the Puter flow');
  });

  test('report-only CSP allows the Puter script, API and sign-in popup origins', () => {
    const vercel = read('vercel.json');
    assert.ok(vercel.includes('https://js.puter.com'), 'CSP script-src must allow the Puter CDN');
    assert.ok(vercel.includes('https://*.puter.com'), 'CSP must allow Puter API/auth origins');
  });
});
