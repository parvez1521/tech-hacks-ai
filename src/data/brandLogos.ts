export function getBrandLogo(slug: string): BrandLogoEntry | undefined {
  if (!slug) return undefined;
  const normalized = slug.toLowerCase().trim();
  const aliased = SLUG_ALIASES[normalized];
  if (aliased && brandLogos[aliased]) {
    return brandLogos[aliased];
  }
  if (brandLogos[normalized]) {
    return brandLogos[normalized];
  }
  const noHyphen = normalized.replace(/-/g, '');
  if (brandLogos[noHyphen]) {
    return brandLogos[noHyphen];
  }
  return undefined;
}

