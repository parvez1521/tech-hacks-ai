export function isOfferActive(offer: AiOffer, referenceDate: Date = new Date()): boolean {
  if (offer.verificationStatus === 'expired' || offer.verificationStatus === 'archived-expired') {
    return false;
  }
  if (offer.verificationStatus === 'pending-verification') {
    return false;
  }
  if (isOfferPastDeadline(offer, referenceDate)) return false;
  return offer.verificationStatus === 'verified-active' || offer.verificationStatus === 'limited-time';
}

export function isOfferPendingVerification(offer: AiOffer): boolean {
  return offer.verificationStatus === 'pending-verification';
}

export function isOfferArchived(offer: AiOffer, referenceDate: Date = new Date()): boolean {
  if (offer.verificationStatus === 'expired' || offer.verificationStatus === 'archived-expired') return true;
  if (isOfferPendingVerification(offer)) return false;
  return isOfferPastDeadline(offer, referenceDate);
}

function isOfferPastDeadline(offer: AiOffer, referenceDate: Date): boolean {
  if (!offer.validUntil) return false;
  const deadline = new Date(offer.validUntil);
  if (Number.isNaN(deadline.getTime())) return false;
  // Date-only offer deadlines include the entire stated calendar day.
  if (/^\d{4}-\d{2}-\d{2}$/.test(offer.validUntil)) deadline.setUTCHours(23, 59, 59, 999);
  return deadline.getTime() < referenceDate.getTime();
}

export function getOfferBySlug(slug: string): AiOffer | undefined {
  return offersData.find((o) => o.slug.toLowerCase() === slug.toLowerCase() || o.id.toLowerCase() === slug.toLowerCase());
}

export function getFeaturedOffers(): AiOffer[] {
  return offersData.filter((o) => o.isFeatured && isOfferActive(o));
}

export function getActiveOffers(): AiOffer[] {
  return offersData.filter((o) => isOfferActive(o));
}

export function getArchivedOffers(): AiOffer[] {
  return offersData.filter((o) => isOfferArchived(o));
}

export function getOffersByType(type: string): AiOffer[] {
  if (type === 'all') return getActiveOffers();
  return getActiveOffers().filter((o) => o.offerType === type);
}
